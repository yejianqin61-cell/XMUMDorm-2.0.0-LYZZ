/**
 * Android 网络安全配置：为校方域名补信 Sectigo R46 / E46 两个**公开根证书**
 *
 * ## 为什么要它（实测，2026-11-14）
 * `l.xmu.edu.my`（Moodle）只发了 `叶子 → Sectigo DV R36` 两张证书，**没发**
 * `R46 ← USERTrust RSA` 的交叉证书（`acad` / `cas` 都发了）。Android ≤13 的系统信任库
 * **没有** R46/E46 根（Android 14+ 的 Conscrypt APEX 才有）→ WebView 报
 * `ERR_CERT_AUTHORITY_INVALID`，Moodle 整页打不开。Chrome 自带根库所以"浏览器能开、App 不能开"。
 * 详见 docs/app/evaluation/校方系统WebView评估与UIUX改进方向.md · W-1。
 *
 * ## 它做什么 / 不做什么
 * ✅ 只对 `xmu.edu.my`（含子域）在系统根之外**多信两个公开根**；证书文件取自 Android 15
 *    系统信任库本身（`/apex/com.android.conscrypt/cacerts/e071171e.0`、`3afde786.0`），
 *    SHA-256 指纹见 `plugins/certs/README.md`。证书校验照常进行（域名、有效期、吊销）。
 * ⛔ 不放行任何证书错误（不写 `onReceivedSslError → proceed()`），不信任用户自装 CA。
 * ⛔ 其它域名完全走系统默认。
 *
 * ## 明文流量
 * 一旦声明了 networkSecurityConfig，`android:usesCleartextTraffic` 在 API 24+ 上会被忽略。
 * 正式包：`base-config cleartextTrafficPermitted="false"`（与不声明时 targetSdk ≥28 的默认一致）。
 * debug / debugOptimized：另写一份同名资源覆盖 main，放行明文，否则连不上 Metro（:8081）和本机后端（:4040）。
 *
 * 根治仍应由校方 IT 在 Moodle 服务器补全证书链；补上后本插件可保留（无副作用）或移除。
 */
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod } = require('@expo/config-plugins');

const SCHOOL_DOMAIN = 'xmu.edu.my';
const ROOTS = ['sectigo_public_server_auth_root_r46', 'sectigo_public_server_auth_root_e46'];
const RESOURCE = 'network_security_config';

function buildXml(cleartext) {
  const anchors = ROOTS.map((name) => `            <certificates src="@raw/${name}" />`).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withSchoolNetworkSecurity.js — do not edit by hand. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="${cleartext}">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>
    <domain-config>
        <domain includeSubdomains="true">${SCHOOL_DOMAIN}</domain>
        <trust-anchors>
            <certificates src="system" />
${anchors}
        </trust-anchors>
    </domain-config>
</network-security-config>
`;
}

function writeFile(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

function withSchoolNetworkSecurity(config) {
  config = withAndroidManifest(config, (mod) => {
    const application = mod.modResults.manifest.application?.[0];
    if (application) {
      application.$ = application.$ ?? {};
      application.$['android:networkSecurityConfig'] = `@xml/${RESOURCE}`;
    }
    return mod;
  });

  return withDangerousMod(config, [
    'android',
    (mod) => {
      const srcDir = path.join(mod.modRequest.platformProjectRoot, 'app', 'src');
      const certDir = path.join(mod.modRequest.projectRoot, 'plugins', 'certs');
      for (const name of ROOTS) {
        writeFile(path.join(srcDir, 'main', 'res', 'raw', `${name}.pem`),
          fs.readFileSync(path.join(certDir, `${name}.pem`), 'utf8'));
      }
      writeFile(path.join(srcDir, 'main', 'res', 'xml', `${RESOURCE}.xml`), buildXml(false));
      for (const variant of ['debug', 'debugOptimized']) {
        writeFile(path.join(srcDir, variant, 'res', 'xml', `${RESOURCE}.xml`), buildXml(true));
      }
      return mod;
    },
  ]);
}

module.exports = withSchoolNetworkSecurity;
module.exports.buildXml = buildXml;
module.exports.ROOTS = ROOTS;
module.exports.SCHOOL_DOMAIN = SCHOOL_DOMAIN;
